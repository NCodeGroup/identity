using MimeKit;

namespace NCode.Identity.Mail.Mime;

/// <summary>
/// Provides the default <see cref="IMimeMessageFactory"/>, which dates a message that names no date by the injected
/// <see cref="TimeProvider"/>.
/// </summary>
/// <param name="timeProvider">The <see cref="TimeProvider"/> that dates a message that names no date.</param>
// See ADR-1532.
internal class DefaultMimeMessageFactory(TimeProvider timeProvider) : IMimeMessageFactory
{
    private const string AutoSubmittedHeaderName = "Auto-Submitted";

    private const string AutoGeneratedValue = "auto-generated";

    private const string ContentHeaderPrefix = "Content-";

    private static HashSet<string> ReservedHeaderNames { get; } =
        new(StringComparer.OrdinalIgnoreCase)
        {
            "From",
            "Sender",
            "Reply-To",
            "To",
            "Cc",
            "Bcc",
            "Subject",
            "Date",
            "Message-Id",
            "In-Reply-To",
            "References",
            "Priority",
            "Importance",
            "X-Priority",
            "MIME-Version",
            "Return-Path",
            "Received",
        };

    /// <summary>
    /// Checks that a mail message can be built into a MIME message.
    /// </summary>
    /// <param name="message">The message to check.</param>
    /// <exception cref="ArgumentException">
    /// Thrown when the message has no recipient in <c>To</c>, <c>Cc</c> or <c>Bcc</c>, has no text body and no HTML
    /// body, has linked resources but no HTML body, or has a custom header that is reserved or whose name starts with
    /// <c>Content-</c>.
    /// </exception>
    private static void Validate(MailMessage message)
    {
        if (message.To.Count == 0 && message.Cc.Count == 0 && message.Bcc.Count == 0)
            throw new ArgumentException(
                "The message must have a recipient in To, Cc or Bcc.",
                nameof(message)
            );

        if (message.TextBody is null && message.HtmlBody is null)
            throw new ArgumentException("The message must have a body.", nameof(message));

        if (message.HtmlBody is null && message.LinkedResources.Count > 0)
            throw new ArgumentException(
                "The message must have an HTML body to link resources to.",
                nameof(message)
            );

        foreach (var header in message.Headers)
        {
            if (
                ReservedHeaderNames.Contains(header.Name)
                || header.Name.StartsWith(ContentHeaderPrefix, StringComparison.OrdinalIgnoreCase)
            )
                throw new ArgumentException(
                    $"The header '{header.Name}' is set by the message's own members and cannot be a custom header.",
                    nameof(message)
                );
        }
    }

    /// <summary>
    /// Converts a mail address to a MIME mailbox address.
    /// </summary>
    /// <param name="address">The address to convert.</param>
    /// <returns>The <see cref="MailboxAddress"/> with the same display name and address.</returns>
    private static MailboxAddress ToMailbox(MailAddress address) =>
        new(address.DisplayName, address.Address);

    /// <summary>
    /// Adds each mail address to a MIME address list, in order.
    /// </summary>
    /// <param name="target">The MIME address list to add the mailboxes to.</param>
    /// <param name="addresses">The mail addresses to add.</param>
    private static void AddAddresses(InternetAddressList target, List<MailAddress> addresses)
    {
        foreach (var address in addresses)
        {
            var mailbox = ToMailbox(address);
            target.Add(mailbox);
        }
    }

    /// <summary>
    /// Maps a mail priority other than normal to the MIME message priority.
    /// </summary>
    /// <param name="priority">The priority to map.</param>
    /// <returns>The <see cref="MessagePriority"/> that matches the priority.</returns>
    /// <exception cref="ArgumentOutOfRangeException">Thrown when the priority is not a defined value.</exception>
    private static MessagePriority ToPriority(MailPriority priority) =>
        priority switch
        {
            MailPriority.NonUrgent => MessagePriority.NonUrgent,
            MailPriority.Urgent => MessagePriority.Urgent,
            _ => throw new ArgumentOutOfRangeException(
                nameof(priority),
                priority,
                "The priority is not a defined value."
            ),
        };

    /// <summary>
    /// Maps a mail importance other than normal to the MIME message importance.
    /// </summary>
    /// <param name="importance">The importance to map.</param>
    /// <returns>The <see cref="MessageImportance"/> that matches the importance.</returns>
    /// <exception cref="ArgumentOutOfRangeException">Thrown when the importance is not a defined value.</exception>
    private static MessageImportance ToImportance(MailImportance importance) =>
        importance switch
        {
            MailImportance.Low => MessageImportance.Low,
            MailImportance.High => MessageImportance.High,
            _ => throw new ArgumentOutOfRangeException(
                nameof(importance),
                importance,
                "The importance is not a defined value."
            ),
        };

    /// <summary>
    /// Maps the name of a content transfer encoding to the MIME content encoding. A content that names no encoding is
    /// encoded as quoted-printable when it is text and as base64 when it is not.
    /// </summary>
    /// <param name="transferEncoding">The name of the transfer encoding, or <see langword="null"/> for the
    /// default.</param>
    /// <param name="isText">Whether the content type is <c>text</c>.</param>
    /// <returns>The <see cref="ContentEncoding"/> to encode the content with.</returns>
    /// <exception cref="ArgumentException">Thrown when the transfer encoding is not a known name.</exception>
    private static ContentEncoding ToEncoding(string? transferEncoding, bool isText)
    {
        if (transferEncoding is null)
            return isText ? ContentEncoding.QuotedPrintable : ContentEncoding.Base64;

        return transferEncoding.ToLowerInvariant() switch
        {
            MailTransferEncodings.SevenBit => ContentEncoding.SevenBit,
            MailTransferEncodings.EightBit => ContentEncoding.EightBit,
            MailTransferEncodings.Binary => ContentEncoding.Binary,
            MailTransferEncodings.QuotedPrintable => ContentEncoding.QuotedPrintable,
            MailTransferEncodings.Base64 => ContentEncoding.Base64,
            _ => throw new ArgumentException(
                $"The transfer encoding '{transferEncoding}' is not known.",
                nameof(transferEncoding)
            ),
        };
    }

    /// <summary>
    /// Creates a MIME part from mail content. The part is a text part when the media type is <c>text</c>, and carries
    /// the content's charset and transfer encoding.
    /// </summary>
    /// <param name="content">The content to build the part from.</param>
    /// <param name="cancellationToken">The <see cref="CancellationToken"/> that may be used to cancel the asynchronous operation.</param>
    /// <returns>A <see cref="ValueTask{TResult}"/> that completes with the MIME part.</returns>
    /// <exception cref="ArgumentException">Thrown when the content's transfer encoding is not a known name.</exception>
    private static async ValueTask<MimePart> CreatePartAsync(
        MailContent content,
        CancellationToken cancellationToken
    )
    {
        await content.LoadIntoBufferAsync(cancellationToken);

        var contentType = ContentType.Parse(content.MediaType);
        var isText = string.Equals(
            contentType.MediaType,
            "text",
            StringComparison.OrdinalIgnoreCase
        );
        var encoding = ToEncoding(content.TransferEncoding, isText);

        MimePart part = isText ? new TextPart(contentType.MediaSubtype) : new MimePart(contentType);
        if (content.Charset is { } charset)
            part.ContentType.Charset = charset;

        var stream = await content.ReadAsStreamAsync(cancellationToken);
        part.Content = new MimeContent(stream);
        part.ContentTransferEncoding = encoding;
        return part;
    }

    /// <summary>
    /// Creates a MIME part from an attachment or a linked resource, with its disposition, file name, content identifier
    /// and description.
    /// </summary>
    /// <param name="attachment">The attachment or linked resource to build the part from.</param>
    /// <param name="disposition">The content disposition of the part, such as inline or attachment.</param>
    /// <param name="cancellationToken">The <see cref="CancellationToken"/> that may be used to cancel the asynchronous operation.</param>
    /// <returns>A <see cref="ValueTask{TResult}"/> that completes with the MIME part.</returns>
    /// <exception cref="ArgumentException">Thrown when the content's transfer encoding is not a known name.</exception>
    private static async ValueTask<MimePart> CreateAttachmentPartAsync(
        MailAttachment attachment,
        string disposition,
        CancellationToken cancellationToken
    )
    {
        var part = await CreatePartAsync(attachment.Content, cancellationToken);
        part.ContentDisposition = new ContentDisposition(disposition);

        if (attachment.FileName is { } fileName)
            part.FileName = fileName;

        if (attachment.ContentId is { } contentId)
            part.ContentId = contentId;

        if (attachment.Description is { } description)
            part.ContentDescription = description;

        return part;
    }

    /// <summary>
    /// Creates the body of a MIME message: the text and HTML parts as alternatives, the linked resources related to the
    /// HTML part, and the attachments in a mixed multipart.
    /// </summary>
    /// <param name="message">The mail message to build the body of.</param>
    /// <param name="cancellationToken">The <see cref="CancellationToken"/> that may be used to cancel the asynchronous operation.</param>
    /// <returns>A <see cref="ValueTask{TResult}"/> that completes with the body entity.</returns>
    /// <exception cref="ArgumentException">
    /// Thrown when the message has no body, a linked resource has no content identifier, or a content's transfer
    /// encoding is not a known name.
    /// </exception>
    private static async ValueTask<MimeEntity> CreateBodyAsync(
        MailMessage message,
        CancellationToken cancellationToken
    )
    {
        MimeEntity? textPart = null;
        if (message.TextBody is { } textBody)
            textPart = await CreatePartAsync(textBody, cancellationToken);

        MimeEntity? htmlPart = null;
        if (message.HtmlBody is { } htmlBody)
        {
            htmlPart = await CreatePartAsync(htmlBody, cancellationToken);

            if (message.LinkedResources.Count > 0)
            {
                var related = new MultipartRelated { htmlPart };
                foreach (var resource in message.LinkedResources)
                {
                    if (string.IsNullOrEmpty(resource.ContentId))
                        throw new ArgumentException(
                            "A linked resource must have a content identifier.",
                            nameof(message)
                        );

                    var resourcePart = await CreateAttachmentPartAsync(
                        resource,
                        ContentDisposition.Inline,
                        cancellationToken
                    );
                    related.Add(resourcePart);
                }

                htmlPart = related;
            }
        }

        MimeEntity body;
        if (textPart is not null && htmlPart is not null)
            body = new MultipartAlternative { textPart, htmlPart };
        else if (textPart is not null)
            body = textPart;
        else if (htmlPart is not null)
            body = htmlPart;
        else
            throw new ArgumentException("The message must have a body.", nameof(message));

        if (message.Attachments.Count == 0)
            return body;

        var mixed = new Multipart("mixed") { body };
        foreach (var attachment in message.Attachments)
        {
            var attachmentPart = await CreateAttachmentPartAsync(
                attachment,
                ContentDisposition.Attachment,
                cancellationToken
            );
            mixed.Add(attachmentPart);
        }

        return mixed;
    }

    private TimeProvider TimeProvider { get; } = timeProvider;

    /// <inheritdoc />
    public FormatOptions CreateFormatOptions()
    {
        var options = FormatOptions.Default.Clone();
        options.HiddenHeaders.Add(HeaderId.Bcc);
        return options;
    }

    /// <inheritdoc />
    public async ValueTask<MimeMessage> CreateAsync(
        MailMessage message,
        MailAddress defaultFrom,
        CancellationToken cancellationToken
    )
    {
        ArgumentNullException.ThrowIfNull(message);
        ArgumentNullException.ThrowIfNull(defaultFrom);

        Validate(message);

        var mimeMessage = new MimeMessage();
        try
        {
            AddHeaders(mimeMessage, message, defaultFrom);
            mimeMessage.Body = await CreateBodyAsync(message, cancellationToken);
            return mimeMessage;
        }
        catch
        {
            mimeMessage.Dispose();
            throw;
        }
    }

    /// <summary>
    /// Sets the headers of a MIME message from a mail message: the sender, the recipients, the subject, the date, or
    /// the current time of the time provider when the message names none, the message identifiers, a priority and an
    /// importance other than normal, and the custom headers. A message without an <c>Auto-Submitted</c> header gets one
    /// with the value <c>auto-generated</c>.
    /// </summary>
    /// <param name="mimeMessage">The MIME message to set the headers of.</param>
    /// <param name="message">The mail message to read the headers from.</param>
    /// <param name="defaultFrom">
    /// The address the message is from when <see cref="MailMessage.From"/> is <see langword="null"/>.
    /// </param>
    /// <exception cref="ArgumentOutOfRangeException">
    /// Thrown when the priority or the importance is not a defined value.
    /// </exception>
    private void AddHeaders(MimeMessage mimeMessage, MailMessage message, MailAddress defaultFrom)
    {
        var from = message.From is { } messageFrom
            ? ToMailbox(messageFrom)
            : new MailboxAddress(
                message.FromDisplayName ?? defaultFrom.DisplayName,
                defaultFrom.Address
            );
        mimeMessage.From.Add(from);

        if (message.Sender is { } sender)
            mimeMessage.Sender = ToMailbox(sender);

        AddAddresses(mimeMessage.ReplyTo, message.ReplyTo);
        AddAddresses(mimeMessage.To, message.To);
        AddAddresses(mimeMessage.Cc, message.Cc);
        AddAddresses(mimeMessage.Bcc, message.Bcc);

        mimeMessage.Subject = message.Subject;
        mimeMessage.Date = message.Date ?? TimeProvider.GetUtcNow();

        if (message.MessageId is { } messageId)
            mimeMessage.MessageId = messageId;

        if (message.InReplyTo is { } inReplyTo)
            mimeMessage.InReplyTo = inReplyTo;

        foreach (var reference in message.References)
            mimeMessage.References.Add(reference);

        if (message.Priority != MailPriority.Normal)
            mimeMessage.Priority = ToPriority(message.Priority);

        if (message.Importance != MailImportance.Normal)
            mimeMessage.Importance = ToImportance(message.Importance);

        var hasAutoSubmitted = false;
        foreach (var header in message.Headers)
        {
            mimeMessage.Headers.Add(header.Name, header.Value);

            if (
                string.Equals(
                    header.Name,
                    AutoSubmittedHeaderName,
                    StringComparison.OrdinalIgnoreCase
                )
            )
                hasAutoSubmitted = true;
        }

        if (!hasAutoSubmitted)
            mimeMessage.Headers.Add(AutoSubmittedHeaderName, AutoGeneratedValue);
    }
}
